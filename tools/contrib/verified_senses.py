"""Lists which own-dictionary senses marked src "storilex" really are the user's contributions.

usage: python3 tools/contrib/verified_senses.py tools/contrib/storilex_contrib.json assets/dict.db lib/data/contrib_verified.dart

tools/contrib/apply.py writes a contributed meaning into an AI draft row of own_word / own_expr
and marks that sense src "storilex"; the row itself stays an unreviewed draft. The label alone is
not proof, so a sense counts as verified only when its Turkish matches a record in
storilex_contrib.json (words, examples, context and phrases in English, and phrase meaning edits):

  exact   the sense's Turkish is the contributed meaning;
  merged  an idiom whose first sense got the contributed wording added to the AI draft's
          ("draft parts, contributed parts"): only the contributed parts are verified.

Anything else stays an unverified draft. The output records the sense's full Turkish too, so the
app checks it is still the same sense (a rebuilt database with other text falls back to draft).
Both input files are only read; the database is opened read-only.
"""
import json
import re
import sqlite3
import sys
from collections import defaultdict

data = json.load(open(sys.argv[1], encoding='utf-8'))
db = sqlite3.connect(f'file:{sys.argv[2]}?mode=ro', uri=True)
out = sys.argv[3]


def norm(t):
    return ' '.join((t or '').lower().split())


def parts(t):
    return [norm(p) for p in re.split(r'[,;]', t or '') if norm(p)]


words = defaultdict(set)
for w in data['words']:
    if w['lang'] == 'en':
        words[w['word'].lower()].add(w['meaning'])
for e in data['examples']:
    if e['lang'] == 'en' and e.get('meaning'):
        words[e['word'].lower()].add(e['meaning'])
for c in data['context']:
    if c['lang'] == 'en' and c.get('meaning'):
        words[c['lemma'].lower()].add(c['meaning'])

phrases = defaultdict(set)
renames = {p['phrase'].lower(): p['to'].lower() for p in data.get('phrase_edits', []) if p['action'] == 'rename'}
for p in data['phrases']:
    if p['lang'] == 'en':
        phrases[renames.get(p['phrase'].lower(), p['phrase'].lower())].add(p['meaning'])
for p in data.get('phrase_edits', []):
    if p['action'] == 'meaning':
        phrases[renames.get(p['phrase'].lower(), p['phrase'].lower())].add(p['meaning'])


def match(tr, records):
    """The verified Turkish of a sense, or None: the record itself, or the record's parts in a merged sense."""
    full = parts(tr)
    for m in sorted(records, key=len, reverse=True):
        if norm(m) == norm(tr):
            return m.strip()
    for m in sorted(records, key=len, reverse=True):
        mp = parts(m)
        if mp and all(p in full for p in mp):
            return ', '.join(x.strip() for x in re.split(r'[,;]', m) if x.strip())
    return None


rows, stats = [], defaultdict(int)
for word, senses in db.execute('SELECT word, senses FROM own_word WHERE reviewed = 0 ORDER BY word'):
    for i, s in enumerate(json.loads(senses)):
        if s.get('src') != 'storilex':
            continue
        v = match(s.get('tr', ''), words[word.lower()])
        stats['words matched' if v else 'words not matched'] += 1
        if v:
            rows.append((f'w:{word}#{i}', s['tr'], v))
for phrase, cat, senses in db.execute('SELECT phrase, cat, senses FROM own_expr WHERE reviewed = 0 ORDER BY phrase, cat'):
    for i, s in enumerate(json.loads(senses)):
        if s.get('src') != 'storilex':
            continue
        v = match(s.get('tr', ''), phrases[phrase.lower()])
        stats['phrases matched' if v else 'phrases not matched'] += 1
        if v:
            rows.append((f'e:{phrase}|{cat}#{i}', s['tr'], v))


def dart(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$') + "'"


with open(out, 'w', encoding='utf-8') as f:
    f.write('// GENERATED by tools/contrib/verified_senses.py from tools/contrib/storilex_contrib.json\n'
            '// and assets/dict.db. Do not edit by hand; run the tool again.\n'
            '//\n'
            '// Senses of AI draft rows (own_word / own_expr, reviewed = 0) marked src "storilex" whose\n'
            '// Turkish matches a contribution record: key -> (the sense\'s full Turkish, verified Turkish).\n'
            f'// {dict(stats)}\n\n'
            'const Map<String, (String, String)> contribVerified = {\n')
    for k, full, v in rows:
        f.write(f'  {dart(k)}: ({dart(full)}, {dart(v)}),\n')
    f.write('};\n')
print(dict(stats))
